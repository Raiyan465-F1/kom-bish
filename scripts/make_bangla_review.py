"""Write docs/bangla_review.md: every Bangla string a farmer can see or hear, as one numbered list.

  python scripts/make_bangla_review.py

Generated from data/clips.csv, data/rules.csv and kombish/texts.py, so the sheet always shows the current
text. Nothing is typed here except the English notes.
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from kombish import texts  # noqa: E402

WIRED = ["consent", "blb", "blast", "safety", "healthy", "not_sure", "voice_failed"]
WHERE = {
    "consent": "Shown at the top of the app and played with the Listen button, before any input",
    "blb": "Answer for bacterial leaf blight (rule R1_BLB): shown and played",
    "blast": "Answer for blast (rule R2_BLAST), only after the farmer answers \"yes\" to the lesion question: shown and played",
    "safety": "Second clip with every blast answer (spray safety): shown and played",
    "healthy": "Answer for a healthy leaf (rule R3_HEALTHY): shown and played. The LAST sentence is the new addition",
    "not_sure": "Referral answer (rules R4, R5, R6, R7): shown and played",
    "voice_failed": "Extra line when a voice note could not be understood (only when voice is switched on)",
}
UI = [   # (name in kombish/texts.py, English meaning, where it appears)
    ("CONSENT_CHECKBOX_BN", "Tick if you agree.", "Label of the consent tick box"),
    ("LABEL_PHOTO_BN", "Photo of a rice leaf", "Photo instruction: label of the photo box"),
    ("LABEL_VOICE_BN", "Voice note (optional)", "Label of the microphone box (only when voice is on)"),
    ("VOICE_PRIVACY_NOTE_BN", "Voice notes are processed on Google's servers", "Under the microphone box"),
    ("SPRAY_INTENT_Q_BN", "Were you thinking of spraying?", "Question above the yes / no choice"),
    ("YES_BN", "Yes", "Answer option (spray question and lesion question)"),
    ("NO_BN", "No", "Answer option (spray question and lesion question)"),
    ("NOT_SURE_BN", "Not sure", "Answer option for the lesion question"),
    ("BUTTON_ADVISE_BN", "Get advice", "The main button"),
    ("LABEL_LISTEN_BN", "Listen", "Label of the audio players"),
    ("LABEL_SAFETY_BN", "Spray safety", "Label of the second audio player"),
    ("AUDIO_SYNTHETIC_NOTE_BN", "Computer-generated voice", "Note beside the audio players"),
    ("CONFIRM_TEMPLATE_BN", "From the photo it looks like your rice has {disease}.", "First line of a BLB or blast answer"),
    ("VOICE_ECHO_BN", "You are saying: \"...\"", "Echo of the voice note (only when voice is on)"),
    ("SOURCE_LABEL_BN", "Source", "Before the source line under an answer"),
    ("FEEDBACK_BN", "This looks wrong", "Feedback button"),
    ("FEEDBACK_THANKS_BN", "Thank you", "After the feedback button is pressed"),
    ("TAB_ADVICE_BN", "Advice", "Tab name"),
    ("TAB_DASHBOARD_BN", "Dashboard", "Tab name"),
]


def read(name: str) -> list[dict]:
    with (ROOT / "data" / name).open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def main() -> int:
    clips = {r["clip_id"]: r for r in read("clips.csv")}
    rules = read("rules.csv")
    manifest_path = ROOT / "audio" / "clips_manifest.json"
    manifest = json.loads(manifest_path.read_text("utf-8")) if manifest_path.exists() else {}
    L = ["# Bangla review sheet", "",
         "Every Bangla string a farmer can see or hear, in one numbered list. Generated by "
         "`python scripts/make_bangla_review.py` from `data/clips.csv`, `data/rules.csv` and `kombish/texts.py`.", "",
         "**Everything here is a DRAFT until one native speaker marks it reviewed.** To approve or change a line, "
         "reply with its number and, if needed, the corrected text. Numbers in spoken scripts are written as "
         "words; the call-centre number is spoken digit by digit.", "",
         "## A. Spoken and shown answers (`data/clips.csv`)", ""]
    n = 0
    for cid in WIRED:
        row, m = clips[cid], manifest.get(cid)
        n += 1
        audio = (f"computer-generated voice, {m['duration_s']} s" + (" (over the 25-second guide)" if m["duration_s"] > 25 else "")
                 if m else "no audio yet")
        L += [f"**{n}. `{cid}`** — {WHERE[cid]}. Status: {row['review_status']}. Audio: {audio}.", "",
              f"> {row['text_bn']}", "", f"English: {row['gloss_en']}", ""]
        if row["text_bn"].strip().upper().startswith("TODO"):
            L += ["**This line does not exist yet. A native speaker must write it.**", ""]
    L += ["## B. Headlines and prompts (`data/rules.csv`)", "",
          "Shown as the heading of each answer. They are not spoken.", ""]
    seen: dict[str, int] = {}
    for r in rules:
        if r["headline_bn"] in seen:
            L += [f"- `{r['rule_id']}` uses line {seen[r['headline_bn']]} again ({r['conditions']}).", ""]
            continue
        n += 1
        seen[r["headline_bn"]] = n
        extra = " **This is the lesion-shape question asked before any blast answer.**" if r["rule_id"] == "R0_CONFIRM_BLAST" else ""
        L += [f"**{n}. `{r['rule_id']}`** — when: {r['conditions']}. Status: {r['review_status']}.{extra}", "",
              f"> {r['headline_bn']}", ""]
    L += ["## C. Buttons, labels and short lines (`kombish/texts.py`)", ""]
    for name, meaning, where in UI:
        n += 1
        L += [f"**{n}. `{name}`** — {where}. English: {meaning}", "", f"> {getattr(texts, name)}", ""]
    for key, value in texts.DISEASE_NAME_BN.items():
        n += 1
        L += [f"**{n}. `DISEASE_NAME_BN[{key}]`** — the disease name inside the confirm line. English: {key.replace('_', ' ')}", "",
              f"> {value}", ""]
    n += 1
    L += [f"**{n}. App title** — top of the page", "", "> কম বিষ (Kom Bish)", "",
          "## D. Lines that do not exist yet", "",
          "- **`voice_failed`** (item 7): one line saying the voice note could not be understood and the advice is "
          "from the photo alone. Needed only if voice is switched on.",
          "- **A photo instruction that asks for a close-up of one leaf.** Today the only photo text is the box label "
          "(`LABEL_PHOTO_BN`) and the no-photo prompt (`R0_NO_PHOTO`). The model works best on a close-up of one "
          "leaf, so a short instruction would help. Not written.", "",
          "Language decision (11 Oct 2026): the app, its answers and its audio are Bangla. The README, model card, "
          "deck, video script, Worker Studio summary and email draft are English. In the app, the \"Show English\" "
          "toggle (off by default) shows the English translation under each answer, headline and prompt; the "
          "English lines are `gloss_en` in `data/clips.csv`, `headline_en` in `data/rules.csv` and the `*_EN` names "
          "in `kombish/texts.py`. If a Bangla line changes, its English line must change with it."]
    out = ROOT / "docs" / "bangla_review.md"
    out.write_text("\n".join(L) + "\n", "utf-8", newline="\n")
    print(f"Wrote {out} ({n} numbered items)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
